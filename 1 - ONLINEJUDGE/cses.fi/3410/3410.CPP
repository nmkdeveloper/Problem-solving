void File(const string &fileName = "")
{
    if (fopen((fileName + ".INP").c_str(), "r"))
    {
        freopen((fileName + ".INP").c_str(), "r", stdin);
        freopen((fileName + ".OUT").c_str(), "w", stdout);
    }
}

int n;

void Read()
{
    cin >> n;
}

ll minu = INF64, maxu = -INF64, minv = INF64, maxv = -INF64;

void Solve()
{
    REP(i, n)
    {
        ll x, y;
        cin >> x >> y;
        ll u = x + y;
        ll v = x - y;
        minu = min(minu, u);
        maxu = max(maxu, u);
        minv = min(minv, v);
        maxv = max(maxv, v);
        if (i == 0)
        {
            cout << 0 << endl;
            continue;
        }
        ll ans = max(maxu - minu, maxv - minv);
        cout << ans << endl;
    }
}

